window.SK_I18N = (function () {
  const root = document.documentElement;
  let lang = root.lang === "ar" ? "ar" : "en";
  const AR = window.SK_AR || {};
  const tr = (en) => (lang === "ar" && AR[en] != null ? AR[en] : en);
  const ATTRS = ["aria-label", "placeholder", "title"];
  const SKIP = "script, style, .wordmark, .intro-name, [data-no-i18n]";

  // Swap static text in place, remembering the English so it can switch back.
  function apply(scope) {
    const base = scope || document.body;
    const walker = document.createTreeWalker(base, NodeFilter.SHOW_TEXT, {
      acceptNode: (n) => (n.parentElement && !n.parentElement.closest(SKIP) && n.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT)
    });
    let n;
    while ((n = walker.nextNode())) {
      if (n.__en == null) n.__en = n.nodeValue;
      const raw = n.__en, key = raw.trim();
      if (AR[key] == null) continue;
      n.nodeValue = lang === "ar" ? raw.replace(key, AR[key]) : raw;
    }
    base.querySelectorAll("[" + ATTRS.join("],[") + "]").forEach((el) => {
      if (el.closest(SKIP)) return;
      ATTRS.forEach((a) => {
        if (!el.hasAttribute(a)) return;
        const store = "__en_" + a;
        if (el[store] == null) el[store] = el.getAttribute(a);
        const en = el[store];
        if (AR[en] != null) el.setAttribute(a, lang === "ar" ? AR[en] : en);
      });
    });
  }

  function set(next) {
    lang = next === "ar" ? "ar" : "en";
    root.lang = lang; root.dir = lang === "ar" ? "rtl" : "ltr";
    try { localStorage.setItem("sk-lang", lang); } catch (e) {}
    if (lang === "ar" && !document.getElementById("ar-fonts")) {
      const f = document.createElement("link"); f.rel = "stylesheet"; f.id = "ar-fonts";
      f.href = "https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Arabic:wght@400;500;600&family=Noto+Kufi+Arabic:wght@400;500&display=swap";
      document.head.appendChild(f);
    }
  }
  return { tr, apply, set, get lang() { return lang; } };
})();
